      `;

      let visibleCount = 0;
      semester.monHoc.forEach((mon, index) => {
        const rowHtml = renderTableRow(
          mon,
          index + 1,
          maxThuongXuyen,
          maxThucHanh,
        );
        if (rowHtml) {
          visibleCount++;
          html += rowHtml;
        }
      });

      html += `
